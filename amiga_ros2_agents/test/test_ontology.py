def test_a_choice_keeps_only_what_both_branches_establish():
    left = ontology.State(frozenset({ontology.Fact(ontology.AT_TREE, "10")}))
    right = ontology.State(frozenset({ontology.Fact(ontology.AT_TREE, "60")}))
    assert left.merge(right).facts == frozenset()
    assert left.merge(left).facts == left.facts


