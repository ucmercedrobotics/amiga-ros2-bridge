"""The action table, against the plans the mission planner actually emits.

``examples/aisle_sample_*.xml`` are three real plans generated by the upstream
GPT mission planner for the three-robot run, one per robot. They are the reason
this module exists: every one of them writes a sampling objective as *enter the
aisle, approach the tree, sample it*, with the aisle move sitting outside the
``RetryUntilSuccessful`` that wraps the other two. Nothing in this system could
see that relationship before, so a task handed to another robot arrived without
the part that gets the robot there.

The table is checked against the schema rather than against a list here, so a
tenth action in ``ActionGroup`` is a failure in this file rather than a leaf
that silently means nothing.
"""

import os
import sys

import pytest
from lxml import etree

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from amiga_ros2_agents.mission import ontology, orchard  # noqa: E402
from amiga_ros2_agents.verification import promela  # noqa: E402

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
EXAMPLES = os.path.join(REPO, "amiga_ros2_behavior_tree", "examples")
SCHEMA = os.path.join(REPO, "amiga_ros2_behavior_tree", "schemas", "amiga_btcpp.xsd")

#: The three-robot demo set, and the aisle each objective is reached from --
#: read off the plans themselves, which is the agreement being pinned.
PLANNER_PLANS = {
    "aisle_sample_10_60.xml": {"10": "10", "60": "6"},
    "aisle_sample_12_62.xml": {"12": "12", "62": "8"},
    "aisle_sample_14_64.xml": {"14": "14", "64": "10"},
}


def example(name: str):
    with open(os.path.join(EXAMPLES, name), "rb") as handle:
        return etree.fromstring(handle.read())


@pytest.fixture(scope="module")
def orchard_map():
    """The real orchard, out of the mission binary the planner produced."""
    return orchard.parse(_orchard_frame("aisle_sample_10_60.bin"))


