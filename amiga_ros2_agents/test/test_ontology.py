@pytest.mark.parametrize("name", sorted(PLANNER_PLANS))
def test_the_planners_own_plans_break_no_precondition(name, orchard_map):
    """The check that gates them, run over the real thing.

    All three write the objective inside a ``RetryUntilSuccessful`` -- the move
    and the sample together -- which the arbiter's old sibling-scoped check
    happened to accept. The one before this rewrite did not accept every shape
    the planner emits, and this is the file that would have caught it.
    """
    assert ontology.violations(example(name), orchard_map) == []


@pytest.mark.parametrize("name", sorted(PLANNER_PLANS))
def test_reaching_a_tree_expects_that_trees_aisle(name, orchard_map):
    """The relationship the whole design turns on.

    Each ``MoveToTreeID`` expects to be in the aisle the orchard puts that tree
    in, and each is preceded by the ``MoveToAisleHead`` that establishes it --
    so nothing is reported missing. That agreement is not arranged here: the
    aisle ids come from the orchard dump and the plan was written by a model
    that never saw this table.
    """
    state = ontology.State()
    expectations = {}
    for element in ontology.actions_in(example(name)):
        step, state = ontology.advance(state, element, orchard_map)
        if step.proposition == ontology.OBJECTIVE:
            need = step.needs[0]
            assert need.kind == ontology.IN_AISLE
            assert need.strength == ontology.EXPECTED
            leaf = element.get("name")
            assert step.missing == (), f"{leaf} is missing {step.missing}"
            expectations[element.get("id")] = need.arg
    assert expectations == PLANNER_PLANS[name]


def test_a_tree_move_without_its_aisle_move_is_allowed_but_noted(orchard_map):
    """Expected, not required -- the distinction the design rests on.

    ``sample_leafs.xml`` reaches both its trees with no aisle move anywhere in
    the plan, and it runs: navigation routes there regardless. Refusing it
    would reject every mission this fleet has ever flown. What the expectation
    buys is knowing the step is *absent*, which is what a planner can be told
    and what a rebuilt task can supply.
    """
    state = ontology.State()
    noted = []
    for element in ontology.actions_in(example("sample_leafs.xml")):
        step, state = ontology.advance(state, element, orchard_map)
        assert step.violation == "", "a missing aisle move must not refuse a plan"
        noted.extend(str(need) for need in step.missing)
    assert noted, "the absent aisle moves should be visible to a planner"
    assert all(note.startswith(ontology.IN_AISLE) for note in noted)


