def test_a_sample_binds_to_the_tree_the_robot_approached():
    """The leaf carries no location; the state is where it gets one."""
    plan = etree.fromstring(
        b'<Sequence><MoveToTreeID name="v" id="60" approach_tree="true"/>'
        b'<SampleLeaf name="s"/></Sequence>'
    )
    state = ontology.State()
    for element in ontology.actions_in(plan):
        step, state = ontology.advance(state, element)
    assert ontology.Fact(ontology.SAMPLED_TREE, "60") in state.facts


def test_driving_past_a_tree_is_not_being_at_it():
    """``approach_tree="false"`` is a waypoint, and sampling from one is wrong.

    The same line the arbiter's ``_objective_tree_ids`` draws. Without it a
    plan could satisfy "sample tree 60" by driving past it.
    """
    plan = etree.fromstring(
        b'<Sequence><MoveToTreeID name="v" id="60" approach_tree="false"/>'
        b'<SampleLeaf name="s"/></Sequence>'
    )
    assert "requires" in " ".join(ontology.violations(plan))


def test_leaving_for_the_aisle_head_ends_being_at_the_tree():
    """A prerequisite step is also a departure.

    Two of the planner's plans drive back out to the aisle head after sampling.
    A state that still claimed the robot was at the tree would let a later
    SampleLeaf bind to a tree the robot has driven away from.
    """
    plan = etree.fromstring(
        b'<Sequence><MoveToTreeID name="v" id="60" approach_tree="true"/>'
        b'<MoveToAisleHead name="out" id="6"/><SampleLeaf name="s"/></Sequence>'
    )
    assert ontology.violations(plan), "the sample has no tree to bind to"


def test_lining_up_at_a_tree_is_not_leaving_it():
    """A relative nudge and a turn are how a plan positions, not how it departs.

    Treating them as travel would make ``approach, nudge, sample`` an orphaned
    sample -- a reasonable plan the fleet would then refuse.
    """
    plan = etree.fromstring(
        b'<Sequence><MoveToTreeID name="v" id="60" approach_tree="true"/>'
        b'<MoveToRelativeLocation name="n" x="0.2" y="0.0"/>'
        b'<OrientRobotHeading name="t" absolute="false" yaw="0.1"/>'
        b'<SampleLeaf name="s"/></Sequence>'
    )
    assert ontology.violations(plan) == []


def test_having_sampled_a_tree_survives_driving_away():
    """Achievement latches; position does not. Same asymmetry promela encodes."""
    plan = etree.fromstring(
        b'<Sequence><MoveToTreeID name="v" id="60" approach_tree="true"/>'
        b'<SampleLeaf name="s"/><MoveToAisleHead name="out" id="6"/></Sequence>'
    )
    state = ontology.State()
    for element in ontology.actions_in(plan):
        _, state = ontology.advance(state, element)
    assert ontology.Fact(ontology.SAMPLED_TREE, "60") in state.facts
    assert state.holding(ontology.AT_TREE) is None


