def test_a_bare_sample_is_refused_by_name():
    """``test_sample_leaf.xml`` is a bring-up rig: it samples nowhere.

    The reason names the element that would fix it rather than the predicate
    that failed, because the reason is handed back to the model that wrote the
    plan and a planner cannot emit an ``at_tree``.
    """
    problems = ontology.violations(example("test_sample_leaf.xml"))
    assert len(problems) == 1
    assert "TestSampleLeaf" in problems[0]
    assert "MoveToTreeID" in problems[0]


def test_a_move_with_no_id_is_a_defect_not_a_missing_prerequisite():
    """Nothing earlier in the plan could have fixed it, so it reads differently."""
    element = etree.fromstring(b'<MoveToTreeID name="v" approach_tree="true"/>')
    step, _ = ontology.advance(ontology.State(), element)
    assert step.defect
    assert "has no id" in step.violation


def test_an_unknown_aisle_is_an_unknown_and_not_a_guess(orchard_map):
    """No orchard means the expectation cannot be bound, never that it failed.

    Every caller treats an unknown aisle as advice it cannot give. A number
    invented here would be a robot sent down the wrong lane.
    """
    element = etree.fromstring(b'<MoveToTreeID name="v" id="60" approach_tree="true"/>')
    without, _ = ontology.advance(ontology.State(), element)
    with_map, _ = ontology.advance(ontology.State(), element, orchard_map)
    assert without.needs[0].arg == ""
    assert with_map.needs[0].arg == "6"


def test_a_control_node_is_not_an_action():
    with pytest.raises(ontology.OntologyError):
        ontology.advance(ontology.State(), etree.fromstring(b"<Sequence/>"))


